"""Table programs that carry CIF-1 fixtures through compiled implementations.

SPEC-09 9.2 (CONF-01) runs every CIF-1 fixture through generated `.ci` table
programs, and SPEC-09 9.8 (CONF-10) observes compiled programs through
`cint-harness`, which reads a case list of `<module> <function> <typed
arguments>` lines and calls each exported function with a fresh context. A
fault ends an entry (SPEC-01 9.4), so each record is its own call.

For a CIF-1 file of one binary operator form, this writes:

- `conformance/tables/<name>.ci`: one exported function applying the operator
  once to its two parameters;
- `conformance/tables/<name>.cases`: one case line per CIF-1 record, in record
  order, so line n of the case list is record n of the CIF-1 file.

`<name>` is the operation identifier with `.` replaced by `_`. The module name
is `tables.<name>`, taking `conformance/` as the source root (SPEC-04 11; the
root is an assumption, ref/OPEN.md O-6).

A wide operand type (I128 to I1024; box 15 note section 5.4) does not pass
through `cint-observe-1`, whose arguments and results are 64-bit patterns
(SPEC-09 CONF-13 X-3). Its table program holds the operands in two module-level
arrays, `a` and `b`, in record order, and its one entry, `row(I64 k)`, prints
the result of record k and returns 0; line n of the case list calls `row` with
k = n - 1.

Only run-time table programs are written. The constant-expression twin that
SPEC-09 CONF-08 asks for is not, because a fault during constant evaluation
rejects the whole module (ref/OPEN.md O-5).

With --kernel, it writes the kernel table of a boundary matrix instead (SPEC-09
CONF-17; SPEC-02 Q-4; box 11 default BX11-18): the operator applied by a kernel,
one work-item per record. `row(k)` dispatches every record that does not fault
in one dispatch and returns the k-th result; `fault_row(k)` dispatches the k-th
record that faults in a dispatch of its own, one work-item. Line n of the case
list is still record n of the CIF-1 file. The files are
`conformance/tables/kernel_<name>.ci` and `.cases`, module
`tables.kernel_<name>`; the expectations are cint_ref's, in format 4.

Usage:
    python gen_tables.py conformance/integer-machine/exh8/add.checked.i8.cif1.jsonl [...] --out conformance/tables/
    python gen_tables.py --kernel conformance/integer-machine/bnd64/*.cif1.jsonl --out conformance/tables/

Python standard library only; no floating point; LF line endings.
"""

import argparse
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import imeval  # noqa: E402

# SPEC-01 4.1 and SPEC-04 3.9: operator spelling per (op, form).
OPERATOR = {
    ("add", "checked"): "+", ("sub", "checked"): "-", ("mul", "checked"): "*",
    ("div", "checked"): "/", ("rem", "checked"): "%",
    ("shl", "checked"): "<<", ("shr", "checked"): ">>",
    ("add", "wrap"): "+%", ("sub", "wrap"): "-%", ("mul", "wrap"): "*%", ("shl", "wrap"): "<<%",
    ("add", "sat"): "+|", ("sub", "sat"): "-|", ("mul", "sat"): "*|",
}

CLAUSE = {
    "add": "SPEC-01 4.1, 4.2", "sub": "SPEC-01 4.1, 4.2", "mul": "SPEC-01 4.1, 4.2",
    "div": "SPEC-01 4.1, 4.4", "rem": "SPEC-01 4.1, 4.4",
    "shl": "SPEC-01 4.1, 4.6", "shr": "SPEC-01 4.1, 4.6",
}


def records(cif_bytes):
    """The records of a CIF-1 file of one binary form, with (op, form, type, name)."""
    recs = [json.loads(line) for line in cif_bytes.decode("utf-8").split("\n") if line]
    if not recs:
        raise ValueError("empty CIF-1 file")
    op_ids = {r["op"] for r in recs}
    if len(op_ids) != 1:
        raise ValueError("a table program covers one operation; found %d" % len(op_ids))
    opid = recs[0]["op"]
    parts = opid.split(".")
    if len(parts) != 3 or (parts[0], parts[1]) not in OPERATOR:
        raise ValueError("not a binary operator form: %s" % opid)
    op, form, t = parts[0], parts[1], parts[2].upper()
    if t not in imeval.TYPES:
        raise ValueError("unknown type in %s" % opid)
    for r in recs:
        if len(r["args"]) != 2 or any(a["t"] != t for a in r["args"]):
            raise ValueError("record %s: expected two %s operands" % (r["id"], t))
    return recs, (op, form, t, opid.replace(".", "_"))


def render(cif_bytes, cif_relpath):
    """Return (program bytes, case-list bytes) for one CIF-1 file of one binary form."""
    recs, (op, form, t, name) = records(cif_bytes)
    if imeval.TYPES[t][1] > 64:
        return render_wide(recs, op, form, t, name, cif_bytes, cif_relpath)
    module = "tables." + name
    subset = "cint-core-1 (saturating forms are outside cint-boot-1, SPEC-09 5.3)" \
        if form == "sat" else "cint-boot-1"
    src = "".join([
        "// conformance/tables/%s.ci\n" % name,
        "// generated by conformance/tools/gen_tables.py; do not edit\n",
        "// source: %s\n" % cif_relpath,
        "// source sha256: %s\n" % hashlib.sha256(cif_bytes).hexdigest(),
        "// records: %d\n" % len(recs),
        "// clause: %s; SPEC-09 9.2 (CONF-01), 9.3, 9.8 (CONF-10)\n" % CLAUSE[op],
        "// subset: %s\n" % subset,
        "// cases: tables/%s.cases (line n is record n of the source)\n" % name,
        "export %s %s(%s a, %s b) {\n" % (t, name, t, t),
        "    return a %s b;\n" % OPERATOR[(op, form)],
        "}\n",
    ])
    cases = "".join("%s %s %s %s %s %s\n" % (module, name, t, r["args"][0]["v"], t, r["args"][1]["v"])
                    for r in recs)
    return src.encode("ascii"), cases.encode("ascii")


def literal(values, indent, per=8):
    """An array literal of decimal values, `per` to a line."""
    rows = [", ".join(values[i:i + per]) for i in range(0, len(values), per)]
    return "[\n%s\n%s]" % (",\n".join(indent + "    " + r for r in rows), indent)


def render_wide(recs, op, form, t, name, cif_bytes, cif_relpath):
    """The table program of a wide operand type (module docstring): the operands in
    module-level arrays, and `row(k)` printing the result of record k."""
    module = "tables." + name
    per = max(1, 512 // imeval.TYPES[t][1])  # lines of about 40 to 310 characters
    src = "".join([
        "// conformance/tables/%s.ci\n" % name,
        "// generated by conformance/tools/gen_tables.py; do not edit\n",
        "// source: %s\n" % cif_relpath,
        "// source sha256: %s\n" % hashlib.sha256(cif_bytes).hexdigest(),
        "// records: %d\n" % len(recs),
        "// clause: %s; SPEC-09 9.2 (CONF-01), 9.3, 9.8 (CONF-10); box 15 note 5.4\n" % CLAUSE[op],
        "// subset: cint-core-1 (wide integer types are outside cint-boot-1, SPEC-09 5.5)\n",
        "// cases: tables/%s.cases (line n is record n of the source): row(k) prints the\n" % name,
        "// result of record k + 1 and returns 0\n",
        "\n",
        "%s[%d] a = %s;\n" % (t, len(recs), literal([r["args"][0]["v"] for r in recs], "", per)),
        "%s[%d] b = %s;\n" % (t, len(recs), literal([r["args"][1]["v"] for r in recs], "", per)),
        "\n",
        "export I64 row(I64 k) {\n",
        "    \"{a[k] %s b[k]}\\n\";\n" % OPERATOR[(op, form)],
        "    return 0;\n",
        "}\n",
    ])
    cases = "".join("%s row I64 %d\n" % (module, k) for k in range(len(recs)))
    return src.encode("ascii"), cases.encode("ascii")


def render_kernel(cif_bytes, cif_relpath):
    """Return (program bytes, case-list bytes) of the kernel table of one CIF-1 file of one
    binary form (SPEC-09 CONF-17): row(k) and fault_row(k), line n of the case list being
    record n of the file."""
    recs, (op, form, t, base) = records(cif_bytes)
    if t != "I64":
        # CONF-17 widens 8- and 16-bit results to I64 outputs (B-16f, CR-11); no such matrix
        # exists yet, so the generator takes the I64 boundary matrices only.
        raise ValueError("a kernel table takes an I64 boundary matrix, not %s" % t)
    name = "kernel_" + base
    module = "tables." + name
    passing = [r for r in recs if "fault" not in r["expect"]]
    faulting = [r for r in recs if "fault" in r["expect"]]
    if not passing:
        raise ValueError("%s: every record faults" % base)

    def operands(rs, k):
        return [r["args"][k]["v"] for r in rs]

    head = [
        "// conformance/tables/%s.ci\n" % name,
        "// generated by conformance/tools/gen_tables.py --kernel; do not edit\n",
        "// source: %s\n" % cif_relpath,
        "// source sha256: %s\n" % hashlib.sha256(cif_bytes).hexdigest(),
        "// records: %d, of which %d fault\n" % (len(recs), len(faulting)),
        "// clause: %s; SPEC-02 Q-4; SPEC-09 9.2 (CONF-01), 9.8 (CONF-10), CONF-17\n" % CLAUSE[op],
        "// subset: cint-core-1 (kernel)\n",
        "// cases: tables/%s.cases (line n is record n of the source): row(k) runs the records\n" % name,
        "// that do not fault in one dispatch and returns the k-th result; fault_row(k) runs the\n",
        "// k-th record that faults in a dispatch of its own\n",
        "\n",
        "kernel apply[n](in %s[n] a, in %s[n] b, out %s[n] r) over [i: n] {\n" % (t, t, t),
        "    r[i] = a[i] %s b[i];\n" % OPERATOR[(op, form)],
        "}\n",
        "\n",
        "export %s row(I64 k) {\n" % t,
        "    %s[%d] a = %s;\n" % (t, len(passing), literal(operands(passing, 0), "    ")),
        "    %s[%d] b = %s;\n" % (t, len(passing), literal(operands(passing, 1), "    ")),
        "    %s[%d] r;\n" % (t, len(passing)),
        "    apply(a, b, r);\n",
        "    return r[k];\n",
        "}\n",
    ]
    if faulting:
        head += [
            "\n",
            "export %s fault_row(I64 k) {\n" % t,
            "    %s[%d] a = %s;\n" % (t, len(faulting), literal(operands(faulting, 0), "    ")),
            "    %s[%d] b = %s;\n" % (t, len(faulting), literal(operands(faulting, 1), "    ")),
            "    %s[1] x = [a[k]];\n" % t,
            "    %s[1] y = [b[k]];\n" % t,
            "    %s[1] r;\n" % t,
            "    apply(x, y, r);\n",
            "    return r[0];\n",
            "}\n",
        ]
    lines, seen = [], {"row": 0, "fault_row": 0}
    for r in recs:
        entry = "fault_row" if "fault" in r["expect"] else "row"
        lines.append("%s %s I64 %d\n" % (module, entry, seen[entry]))
        seen[entry] += 1
    return "".join(head).encode("ascii"), "".join(lines).encode("ascii")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("cif", nargs="+")
    p.add_argument("--out", required=True)
    p.add_argument("--kernel", action="store_true",
                   help="write the kernel table of each I64 boundary matrix (SPEC-09 CONF-17)")
    p.add_argument("--root", default="conformance",
                   help="directory that source paths in the header are relative to")
    args = p.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    for path in args.cif:
        with open(path, "rb") as fh:
            data = fh.read()
        rel = os.path.relpath(path, args.root).replace(os.sep, "/")
        src, cases = (render_kernel if args.kernel else render)(data, rel)
        name = ("kernel_" if args.kernel else "") + \
            json.loads(data.split(b"\n", 1)[0])["op"].replace(".", "_")
        for ext, blob in ((".ci", src), (".cases", cases)):
            out = os.path.join(args.out, name + ext)
            imeval.write_bytes(out, blob)
            print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
